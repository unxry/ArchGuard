'use strict';
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { pathToFileURL } = require('node:url');
const { chromium } = require('playwright');
const root = __dirname;
(async () => {
 const browser = await chromium.launch({headless:true});
 const context = await browser.newContext({viewport:{width:1440,height:900},deviceScaleFactor:1,offline:true,acceptDownloads:true});
 const page = await context.newPage();
 const errors=[], externalRequests=[], checks=[], timings={};
 page.on('pageerror',e=>errors.push(e.message));
 page.on('console',m=>{if(m.type()==='error') errors.push(m.text());});
 page.on('request',r=>{if(/^https?:/.test(r.url()))externalRequests.push(r.url());});
 const check=(name,value)=>{assert.ok(value,name);checks.push(name);};
 const state=()=>page.evaluate(()=>window.STRATA.getState());
 const capture=async filename=>{await page.mouse.move(0,0);return page.screenshot({path:path.join(root,filename),animations:'disabled'});};
 const settle=()=>page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
 await page.goto(pathToFileURL(path.join(root,'index.html')).href);
 await settle();
 check('file:// loads offline', (await state()).nodeCount===12);
 check('No desktop page overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth&&document.body.scrollHeight<=innerHeight));
 await capture('preview-overview.png');
 await page.locator('[data-node="checkout"]').click();
 check('Node inspector shows selection',await page.locator('#inspectorContent h2').textContent()==='Checkout API');
 await page.locator('#focusGraph').click();
 check('Focus dims unrelated graph',await page.locator('.graph-node.dimmed').count()>0);
 await page.locator('#zoomIn').click();await settle();
 check('Zoom changes scale',(await state()).zoom>1);
 await page.locator('[data-view="findings"]').click();
 await page.locator('[data-view="atlas"]').click();
 check('Node and zoom survive workspace navigation',(await state()).node==='checkout'&&(await state()).zoom>1);
 await capture('preview-graph.png');
 await page.locator('#fitGraph').click();await settle();
 const graph=await page.locator('#graph').boundingBox();
 await page.mouse.move(graph.x+25,graph.y+20);await page.mouse.down();await page.mouse.move(graph.x+70,graph.y+42,{steps:4});await page.mouse.up();await settle();
 check('Pan changes world transform',Math.abs((await state()).panX)>1);
 await page.locator('#fitGraph').click();
 await page.locator('#overlayButton').click();check('Overlay toggles all violation markers',await page.locator('.graph-edge.hot,.graph-node.issue').count()===0);
 await page.locator('#overlayButton').click();
 await page.locator('#search').fill('not-in-this-demo');check('Search provides empty state',await page.locator('#graphEmpty').isVisible());
 await page.locator('#graphEmpty [data-action="clear-search"]').click();
 await page.locator('#search').fill('ARCH001');check('Rule search highlights graph',await page.locator('.graph-node:not(.dimmed)').count()===2);
 await page.locator('#search').fill('');
 await page.locator('[data-view="findings"]').click();
 await page.locator('#namespaceFilter').selectOption('SEC');check('Namespace filter uses data',await page.locator('.finding-row').count()===3);
 await page.locator('#stateFilter').selectOption('confirmed');check('Evidence filter keeps supported only',await page.locator('.finding-row').count()===1);
 await page.locator('#severityFilter').selectOption('LOW');check('Empty filtered queue has reset',await page.locator('[data-action="reset-filters"]').isVisible());
 await page.locator('[data-action="reset-filters"]').click();
 await page.locator('[data-finding="sec-002"]').click();
 await page.locator('[data-source="1"]').click();
 check('Evidence opens exact source excerpt',await page.locator('.code-block').textContent().then(t=>t.includes('pool.query')));
 await page.setViewportSize({width:1920,height:1080});await settle();
 await page.locator('#inspector').evaluate(el=>el.scrollTop=0);
 await capture('preview-finding.png');
 await page.locator('[data-view="coverage"]').click();
 check('Coverage separates ten rules',await page.locator('[data-coverage]').count()===10);
 await page.locator('[data-coverage="SEC005"]').click();check('Unsupported is not safe',await page.locator('#inspectorContent').textContent().then(t=>t.includes('Not evaluated for TypeScript')&&t.includes('Unsupported')));
 await page.locator('[data-coverage="SEC008"]').click();check('Scoped negative has explicit certificate',await page.locator('.certificate').count()===1);
 check('Negative never certifies repository',await page.locator('#inspectorContent').textContent().then(t=>t.includes('This is not “repository secure”')));
 await page.locator('#inspector').evaluate(el=>el.scrollTop=0);await capture('preview-coverage.png');
 const downloadEvent=page.waitForEvent('download');await page.locator('#exportButton').click();const download=await downloadEvent;
 const payload=JSON.parse(fs.readFileSync(await download.path(),'utf8'));
 check('Export is marked synthetic with no integration',payload.synthetic===true&&payload.backendConnected===false&&payload.label==='DEMO DATA');
 await page.locator('#scenario').selectOption('dense');
 const density=await page.evaluate(async()=>{const start=performance.now();document.querySelector('[data-view="atlas"]').click();await new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)));return performance.now()-start;});
 timings.denseViewInteractionMs=Math.round(density*10)/10;
 check('Dense graph scenario works',(await state()).nodeCount===40&&(await state()).edgeCount===74);
 await page.locator('#fitGraph').click();await capture('preview-dense.png');
 const startMany=performance.now();await page.locator('#scenario').selectOption('many');await settle();timings.manyScenarioInteractionMs=Math.round((performance.now()-startMany)*10)/10;
 check('Large queue is bounded to six DOM records',(await state()).findingCount===240&&await page.locator('.finding-row').count()===6);
 await page.locator('#nextPage').click();check('Pagination changes records',await page.locator('#pageCount').textContent()==='Page 2 of 40');
 await page.locator('#namespaceFilter').selectOption('SEC');check('Pagination reflects filtering',await page.locator('#pageCount').textContent()==='Page 1 of 20');
 await page.locator('#scenario').selectOption('small');await page.locator('[data-view="atlas"]').click();
 await page.keyboard.press('/');check('Search keyboard shortcut',await page.locator('#search').evaluate(el=>el===document.activeElement));
 await page.locator('[data-node="orders"]').focus();await page.keyboard.press('Enter');check('Keyboard node selection',(await state()).node==='orders');
 await page.keyboard.press('ArrowRight');check('Keyboard traverses graph nodes',await page.evaluate(()=>document.activeElement.dataset.node)==='catalog');
 await page.locator('#closeInspector').click();check('Close restores focus',await page.locator('#inspectorToggle').evaluate(el=>el===document.activeElement));
 await page.locator('#inspectorToggle').click();
 await page.locator('#guideButton').click();check('Guide dialog opens',await page.locator('#guide').evaluate(el=>el.open));
 await page.keyboard.press('Escape');check('Escape closes dialog',!await page.locator('#guide').evaluate(el=>el.open));
 await page.locator('[data-view="findings"]').click();await page.locator('[data-finding="arch-001"]').click();
 await page.locator('#evidenceTab').focus();await page.keyboard.press('ArrowRight');check('Detail tabs support arrow keys',await page.locator('#sourceTab').getAttribute('aria-selected')==='true');
 await page.emulateMedia({reducedMotion:'reduce'});
 check('Reduced motion disables transitions',await page.locator('.view').first().evaluate(el=>getComputedStyle(el).animationName)==='none');
 await page.locator('[data-view="atlas"]').click();await page.locator('#scenario').selectOption('small');await capture('preview-reduced-motion.png');
 await page.setViewportSize({width:390,height:844});await page.reload();await settle();
 check('390px has no horizontal page overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 check('Mobile map uses readable focused viewport',await page.locator('#graph').getAttribute('viewBox')==='20 60 460 480');
 await capture('preview-mobile.png');
 await page.locator('[data-view="findings"]').click();await page.locator('[data-finding="sec-006"]').click();
 check('Mobile finding scrolls to dossier',await page.locator('#inspector').evaluate(el=>el.getBoundingClientRect().top<100));
 await capture('preview-mobile-finding.png');
 await page.setViewportSize({width:320,height:740});await settle();
 check('320px has no horizontal page overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.setViewportSize({width:768,height:1024});await page.reload();await settle();
 check('Tablet has no horizontal page overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 check('No JavaScript or console errors',errors.length===0);check('No external network requests',externalRequests.length===0);
 const report={browser:await browser.version(),transport:'file://',offline:true,checks:checks.length,passed:checks,errors,externalRequests,timings,viewports:['1440×900','1920×1080','390×844','320×740','768×1024'],note:'Timings are single-run local interaction observations, not a frame-rate guarantee.'};
 fs.writeFileSync(path.join(root,'browser-check-results.json'),JSON.stringify(report,null,2)+'\n');
 console.log(JSON.stringify(report,null,2));await browser.close();
})().catch(error=>{console.error(error.stack);process.exit(1);});
